package initcfg

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Ramanan-Bala/donegate/internal/policy"
	"github.com/bmatcuk/doublestar/v4"
	"gopkg.in/yaml.v3"
)

// Result describes the detected stack and generated project entries for a repository.
type Result struct {
	Root           string
	PackageManager string
	Projects       []policy.Project
}

type packageJSON struct {
	Name            string            `json:"name"`
	Scripts         map[string]string `json:"scripts"`
	Dependencies    map[string]string `json:"dependencies"`
	DevDependencies map[string]string `json:"devDependencies"`
	Workspaces      json.RawMessage   `json:"workspaces"`
}

type pnpmWorkspaceYAML struct {
	Packages []string `yaml:"packages"`
}

type renderConfig struct {
	Version  int             `yaml:"version"`
	Projects []renderProject `yaml:"projects"`
	Protect  policy.Protect  `yaml:"protect"`
	Gate     policy.Gate     `yaml:"gate"`
}

type renderProject struct {
	Name      string `yaml:"name"`
	Root      string `yaml:"root"`
	Test      string `yaml:"test,omitempty"`
	Typecheck string `yaml:"typecheck,omitempty"`
	Lint      string `yaml:"lint,omitempty"`
}

// Detect inspects root and infers the package manager, projects, and verification commands.
func Detect(root string) (Result, error) {
	if root == "" {
		root = "."
	}
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return Result{}, fmt.Errorf("detect stack: %w", err)
	}
	info, err := os.Stat(absRoot)
	if err != nil {
		return Result{}, fmt.Errorf("detect stack: %w", err)
	}
	if !info.IsDir() {
		return Result{}, fmt.Errorf("detect stack: %s is not a directory", root)
	}

	rootPkgPath := filepath.Join(absRoot, "package.json")
	if !fileExists(rootPkgPath) {
		goModPath := filepath.Join(absRoot, "go.mod")
		if fileExists(goModPath) {
			name := detectGoProjectName(goModPath, absRoot)
			return Result{
				Root: absRoot,
				Projects: []policy.Project{
					{
						Name:      name,
						Root:      "",
						Test:      "go test -count=1 ./...",
						Typecheck: "go vet ./...",
					},
				},
			}, nil
		}
		return Result{}, fmt.Errorf("detect stack: no supported project found in %s", root)
	}

	pm := detectPackageManager(absRoot)
	pmExec := packageManagerExec(pm)

	rootPkg, err := readPackageJSON(rootPkgPath)
	if err != nil {
		return Result{}, fmt.Errorf("detect stack: %w", err)
	}

	wsGlobs, err := readWorkspaceGlobs(absRoot, rootPkg)
	if err != nil {
		return Result{}, fmt.Errorf("detect stack: %w", err)
	}

	var projects []policy.Project
	if len(wsGlobs) > 0 {
		dirs, err := expandWorkspaceDirs(absRoot, wsGlobs)
		if err != nil {
			return Result{}, fmt.Errorf("detect stack: %w", err)
		}
		for _, relDir := range dirs {
			projDir := filepath.Join(absRoot, filepath.FromSlash(relDir))
			proj, err := detectJSProject(projDir, relDir, path.Base(relDir), pm, pmExec, nil)
			if err != nil {
				return Result{}, fmt.Errorf("detect stack: %w", err)
			}
			projects = append(projects, proj)
		}
	}

	if len(projects) == 0 {
		proj, err := detectJSProject(absRoot, "", defaultDirName(absRoot), pm, pmExec, &rootPkg)
		if err != nil {
			return Result{}, fmt.Errorf("detect stack: %w", err)
		}
		projects = []policy.Project{proj}
	}

	return Result{
		Root:           absRoot,
		PackageManager: pm,
		Projects:       projects,
	}, nil
}

// Render formats res as a starter .donegate.yml using internal/policy defaults.
func Render(res Result) ([]byte, error) {
	def := policy.Default()

	projects := make([]renderProject, 0, len(res.Projects))
	for _, p := range res.Projects {
		projects = append(projects, renderProject{
			Name:      p.Name,
			Root:      p.Root,
			Test:      p.Test,
			Typecheck: p.Typecheck,
			Lint:      p.Lint,
		})
	}

	protect := def.Protect
	if res.PackageManager == "" {
		// Go fallback: the JS-oriented default globs would protect nothing.
		protect.Tests = []string{"**/*_test.go", "**/testdata/**"}
		protect.Config = []string{".github/workflows/**", ".golangci.yml"}
	}

	cfg := renderConfig{
		Version:  def.Version,
		Projects: projects,
		Protect:  protect,
		Gate:     def.Gate,
	}

	var body bytes.Buffer
	enc := yaml.NewEncoder(&body)
	enc.SetIndent(2)
	if err := enc.Encode(cfg); err != nil {
		return nil, fmt.Errorf("render config: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("render config: %w", err)
	}

	header := "# Generated by donegate init.\n# Review commands and protected globs for your repository.\n"
	out := make([]byte, 0, len(header)+body.Len())
	out = append(out, header...)
	out = append(out, body.Bytes()...)
	return out, nil
}

func detectPackageManager(root string) string {
	switch {
	case fileExists(filepath.Join(root, "pnpm-lock.yaml")):
		return "pnpm"
	case fileExists(filepath.Join(root, "yarn.lock")):
		return "yarn"
	case fileExists(filepath.Join(root, "bun.lockb")) || fileExists(filepath.Join(root, "bun.lock")):
		return "bun"
	default:
		return "npm"
	}
}

func packageManagerExec(pm string) string {
	switch pm {
	case "pnpm":
		return "pnpm exec"
	case "yarn":
		return "yarn"
	case "bun":
		return "bunx"
	default:
		return "npx"
	}
}

func readPackageJSON(pkgPath string) (packageJSON, error) {
	data, err := os.ReadFile(pkgPath)
	if err != nil {
		return packageJSON{}, fmt.Errorf("read %s: %w", pkgPath, err)
	}
	var pkg packageJSON
	if err := json.Unmarshal(data, &pkg); err != nil {
		return packageJSON{}, fmt.Errorf("parse %s: %w", pkgPath, err)
	}
	return pkg, nil
}

func readWorkspaceGlobs(root string, rootPkg packageJSON) ([]string, error) {
	pnpmPath := filepath.Join(root, "pnpm-workspace.yaml")
	if fileExists(pnpmPath) {
		data, err := os.ReadFile(pnpmPath)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", pnpmPath, err)
		}
		var ws pnpmWorkspaceYAML
		if err := yaml.Unmarshal(data, &ws); err != nil {
			return nil, fmt.Errorf("parse %s: %w", pnpmPath, err)
		}
		if len(ws.Packages) > 0 {
			return ws.Packages, nil
		}
	}

	raw := bytes.TrimSpace(rootPkg.Workspaces)
	if len(raw) == 0 || bytes.Equal(raw, []byte("null")) {
		return nil, nil
	}

	var arr []string
	if err := json.Unmarshal(raw, &arr); err == nil {
		return arr, nil
	}

	var obj struct {
		Packages []string `json:"packages"`
	}
	if err := json.Unmarshal(raw, &obj); err != nil {
		return nil, fmt.Errorf("parse workspaces: %w", err)
	}
	return obj.Packages, nil
}

func expandWorkspaceDirs(root string, globs []string) ([]string, error) {
	fsys := os.DirFS(root)
	candidates := make(map[string]bool)
	var excludes []string

	for _, raw := range globs {
		pat := strings.TrimSpace(raw)
		if pat == "" {
			continue
		}
		if strings.HasPrefix(pat, "!") {
			neg := normalizeWorkspaceGlob(strings.TrimPrefix(pat, "!"))
			if neg != "" {
				excludes = append(excludes, neg)
			}
			continue
		}

		norm := normalizeWorkspaceGlob(pat)
		if norm == "" {
			continue
		}
		pkgGlob := norm
		if pkgGlob != "package.json" && !strings.HasSuffix(pkgGlob, "/package.json") {
			pkgGlob = path.Join(pkgGlob, "package.json")
		}

		matches, err := doublestar.Glob(fsys, pkgGlob)
		if err != nil {
			return nil, fmt.Errorf("expand workspace glob %q: %w", raw, err)
		}
		for _, m := range matches {
			dir := path.Dir(m)
			if dir == "." || hasPathSegment(dir, "node_modules") {
				continue
			}
			candidates[dir] = true
		}
	}

	for _, excl := range excludes {
		for dir := range candidates {
			if matchExclude(excl, dir) {
				delete(candidates, dir)
			}
		}
	}

	dirs := make([]string, 0, len(candidates))
	for dir := range candidates {
		dirs = append(dirs, dir)
	}
	sort.Strings(dirs)
	return dirs, nil
}

func normalizeWorkspaceGlob(raw string) string {
	s := strings.TrimSpace(raw)
	s = filepath.ToSlash(s)
	s = strings.TrimPrefix(s, "./")
	s = strings.TrimSuffix(s, "/")
	return s
}

func matchExclude(pattern, dir string) bool {
	if ok, err := doublestar.Match(pattern, dir); err == nil && ok {
		return true
	}
	if ok, err := doublestar.Match(path.Join(pattern, "**"), dir); err == nil && ok {
		return true
	}
	return false
}

func hasPathSegment(slashPath, segment string) bool {
	for _, part := range strings.Split(slashPath, "/") {
		if part == segment {
			return true
		}
	}
	return false
}

func detectJSProject(projDir, relRoot, fallbackName, pm, pmExec string, preloaded *packageJSON) (policy.Project, error) {
	var pkg packageJSON
	if preloaded != nil {
		pkg = *preloaded
	} else {
		var err error
		pkg, err = readPackageJSON(filepath.Join(projDir, "package.json"))
		if err != nil {
			return policy.Project{}, err
		}
	}

	name := strings.TrimSpace(pkg.Name)
	if name == "" {
		name = fallbackName
	}

	var testCmd string
	switch detectJSTestRunner(projDir, pkg) {
	case "vitest":
		testCmd = pmExec + " vitest run --reporter=json --outputFile={json}"
	case "jest":
		testCmd = pmExec + " jest --json --outputFile={json}"
	default:
		if strings.TrimSpace(pkg.Scripts["test"]) != "" {
			testCmd = pm + " test"
		}
	}

	var typecheckCmd string
	if fileExists(filepath.Join(projDir, "tsconfig.json")) {
		typecheckCmd = pmExec + " tsc --noEmit"
	}

	var lintCmd string
	if strings.TrimSpace(pkg.Scripts["lint"]) != "" {
		lintCmd = pm + " run lint"
	}

	return policy.Project{
		Name:      name,
		Root:      relRoot,
		Test:      testCmd,
		Typecheck: typecheckCmd,
		Lint:      lintCmd,
	}, nil
}

func detectJSTestRunner(projDir string, pkg packageJSON) string {
	if hasPackageDep(pkg, "vitest") || hasFilePrefix(projDir, "vitest.config.") {
		return "vitest"
	}
	if hasPackageDep(pkg, "jest") || hasFilePrefix(projDir, "jest.config.") {
		return "jest"
	}
	return "none"
}

func hasPackageDep(pkg packageJSON, name string) bool {
	if _, ok := pkg.Dependencies[name]; ok {
		return true
	}
	if _, ok := pkg.DevDependencies[name]; ok {
		return true
	}
	return false
}

func hasFilePrefix(dir, prefix string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		if strings.HasPrefix(entry.Name(), prefix) {
			return true
		}
	}
	return false
}

func detectGoProjectName(goModPath, absRoot string) string {
	data, err := os.ReadFile(goModPath)
	if err == nil {
		for _, line := range strings.Split(string(data), "\n") {
			fields := strings.Fields(line)
			if len(fields) >= 2 && fields[0] == "module" {
				mod := strings.Trim(fields[1], `"'`)
				base := path.Base(mod)
				if base != "" && base != "." && base != "/" {
					return base
				}
				break
			}
		}
	}
	return defaultDirName(absRoot)
}

func defaultDirName(absRoot string) string {
	base := filepath.Base(absRoot)
	if base == "" || base == "." || base == string(filepath.Separator) {
		return "app"
	}
	return base
}

func fileExists(p string) bool {
	info, err := os.Stat(p)
	if err != nil {
		return false
	}
	return !info.IsDir()
}
